// Runtime bounds fit the fixed 10-bit X/9-bit Y raster; input validity remains full-width.
`timescale 1ns/1ps

// ============================================================================
// D5-A1
// Fixed 640x480 target-frame scan / fitted-image region generator.
//
// Purpose:
//   - Scan exactly one 640x480 destination frame in raster order.
//   - Classify every destination pixel as:
//         * fitted image region, or
//         * letterbox / pillarbox black-border region.
//   - For image pixels, provide coordinates local to the fitted image.
//   - Provide a sequential 0..307199 destination-frame address.
//
// This module DOES NOT perform scaling and DOES NOT access SDRAM.
// It is the front-end coordinate generator for the later D5 Bilinear Scaler.
//
// Contract:
//   1) cfg_load latches one geometry snapshot.
//   2) start resets the output scan to destination pixel (0,0).
//   3) advance consumes exactly one destination pixel.
//   4) done pulses for one clk after the final pixel (639,479) is consumed.
//
// Verilog-2001 compatible.
// No runtime multiplication or division.
// ============================================================================

module scaler_dst_scan_gen #(
    parameter OUT_WIDTH  = 640,
    parameter OUT_HEIGHT = 480,
    parameter ADDR_BITS  = 19
)(
    input                   clk,
    input                   rst,

    // Geometry generated by adaptive_image_fit.
    input                   cfg_load,
    input      [15:0]       dst_width,
    input      [15:0]       dst_height,
    input      [15:0]       x_offset,
    input      [15:0]       y_offset,
    input                   geometry_valid,

    output reg              cfg_valid,

    // Destination-frame scan control.
    input                   start,
    input                   advance,

    output reg              scan_active,
    output reg              done,

    // Current HDMI/destination coordinate.
    output reg [9:0]        out_x,
    output reg [8:0]        out_y,

    // Linear address inside one 640x480 DISPLAY_BUF.
    output reg [ADDR_BITS-1:0] dst_addr,

    // Current pixel classification.
    output reg              inside_image,

    // Coordinate inside the fitted image rectangle.
    // Valid only when inside_image == 1.
    output reg [15:0]       image_x,
    output reg [15:0]       image_y,

    // High on the current final destination pixel.
    output                  frame_last
);

    reg [15:0] cfg_dst_width;
    reg [15:0] cfg_dst_height;
    reg [9:0] cfg_x_offset;
    reg [8:0] cfg_y_offset;
    reg [10:0] cfg_x_end;
    reg [9:0] cfg_y_end;

    // Coordinates for the pixel that follows the currently presented pixel.
    wire [9:0] next_x =
        (out_x == OUT_WIDTH - 1) ?
        10'd0 :
        (out_x + 1'b1);

    wire [8:0] next_y =
        (out_x == OUT_WIDTH - 1) ?
        (out_y + 1'b1) :
        out_y;

    // This classification cone terminates at the registered scan outputs.
    wire next_inside =
        cfg_valid &&
        ({7'd0, next_x} >= {1'b0, cfg_x_offset}) &&
        ({7'd0, next_x} <  cfg_x_end) &&
        ({8'd0, next_y} >= {1'b0, cfg_y_offset}) &&
        ({8'd0, next_y} <  cfg_y_end);

    wire [15:0] next_image_x =
        next_inside ?
        ({6'd0, next_x} - cfg_x_offset) :
        16'd0;

    wire [15:0] next_image_y =
        next_inside ?
        ({7'd0, next_y} - cfg_y_offset) :
        16'd0;

    // Classification for destination pixel (0,0), loaded together with start.
    wire start_inside =
        cfg_valid &&
        (17'd0 >= {1'b0, cfg_x_offset}) &&
        (17'd0 <  cfg_x_end) &&
        (17'd0 >= {1'b0, cfg_y_offset}) &&
        (17'd0 <  cfg_y_end);

    assign frame_last =
        scan_active &&
        (out_x == OUT_WIDTH  - 1) &&
        (out_y == OUT_HEIGHT - 1);


    // ------------------------------------------------------------------------
    // Geometry snapshot.
    // Reject any rectangle that does not fit completely inside 640x480.
    // ------------------------------------------------------------------------
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            cfg_dst_width  <= 16'd0;
            cfg_dst_height <= 16'd0;
            cfg_x_offset   <= 16'd0;
            cfg_y_offset   <= 16'd0;
            cfg_x_end      <= 17'd0;
            cfg_y_end      <= 17'd0;
            cfg_valid      <= 1'b0;
        end
        else if (cfg_load) begin
            cfg_dst_width  <= dst_width;
            cfg_dst_height <= dst_height;
            cfg_x_offset   <= x_offset;
            cfg_y_offset   <= y_offset;
            cfg_x_end      <= {1'b0, x_offset} + {1'b0, dst_width};
            cfg_y_end      <= {1'b0, y_offset} + {1'b0, dst_height};

            if (
                geometry_valid &&
                (dst_width  != 16'd0) &&
                (dst_height != 16'd0) &&
                ({1'b0, x_offset} + {1'b0, dst_width}  <= OUT_WIDTH) &&
                ({1'b0, y_offset} + {1'b0, dst_height} <= OUT_HEIGHT)
            )
                cfg_valid <= 1'b1;
            else
                cfg_valid <= 1'b0;
        end
    end


    // ------------------------------------------------------------------------
    // 640x480 raster scan.
    // dst_addr is intentionally a counter, not y*640+x.
    // ------------------------------------------------------------------------
    always @(posedge clk or posedge rst) begin
        if (rst) begin
            scan_active <= 1'b0;
            done        <= 1'b0;

            out_x    <= 10'd0;
            out_y    <= 9'd0;
            dst_addr <= {ADDR_BITS{1'b0}};

            inside_image <= 1'b0;
            image_x      <= 16'd0;
            image_y      <= 16'd0;
        end
        else begin
            done <= 1'b0;

            if (start) begin
                out_x    <= 10'd0;
                out_y    <= 9'd0;
                dst_addr <= {ADDR_BITS{1'b0}};

                inside_image <= start_inside;
                image_x      <= 16'd0;
                image_y      <= 16'd0;

                scan_active <= cfg_valid;
            end
            else if (scan_active && advance) begin

                if (
                    (out_x == OUT_WIDTH  - 1) &&
                    (out_y == OUT_HEIGHT - 1)
                ) begin
                    // Final pixel has just been consumed.
                    scan_active <= 1'b0;
                    done        <= 1'b1;

                    inside_image <= 1'b0;
                    image_x      <= 16'd0;
                    image_y      <= 16'd0;
                end
                else begin
                    dst_addr <= dst_addr + 1'b1;
                    out_x    <= next_x;
                    out_y    <= next_y;

                    inside_image <= next_inside;
                    image_x      <= next_image_x;
                    image_y      <= next_image_y;
                end
            end
        end
    end

endmodule
